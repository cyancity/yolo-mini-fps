// 双层增高架。下层是一体铣出来的多用途增高架：左侧一根长夹板咬住机匣导轨，顶上后高前低两段导轨，
// 前面那段悬空探出去，镭射装在上面；上层是夹在后平台上的镂空支架，两片侧板撑起顶板，前后通透
import { rbox, cylBetween, xf } from '../gfx/geo.js';
import { ex, SIDE, chamfer, fillet, screw, rail, railClamp, RAIL_Y, RAIL_SLIM } from './rifle_kit.js';
import { OPTIC } from './rifle_optics.js';

const Z = OPTIC.z;
// 下层本体的顶面（后平台的导轨底座压在上面）和前伸段的齿顶，都相对机匣导轨的齿顶
const P = OPTIC.lo - RAIL_Y - 0.0081, E = OPTIC.ext - RAIL_Y;
// 下层的夹爪截面 [x, y]（y 相对被夹导轨的齿顶）：右边和本体连成一体，左边是单独的夹板，顶面矮一点、和底板之间留一道缝
const JAW_FIX = [[0.011, 0.003], [0.0152, 0.003], [0.0152, -0.0052], [0.014, -0.0064], [0.0088, -0.0064], [0.0088, -0.005], [0.011, -0.0028]];
const JAW_BAR = [[-0.0112, 0.0026], [-0.0154, 0.0026], [-0.0154, -0.0052], [-0.0142, -0.0064], [-0.0088, -0.0064], [-0.0088, -0.005], [-0.0112, -0.0028]];
// 夹板上包着横栓头的凸台，侧视是削了角的八边形 [z, y]
const BOSS = [[-0.0065, -0.003], [-0.0038, -0.0062], [0.0038, -0.0062], [0.0065, -0.003], [0.0065, 0.0004], [0.0045, 0.0024], [-0.0045, 0.0024], [-0.0065, 0.0004]];

export function buildLowerRiser(k) {
  // 侧视轮廓 [z, y]：z 相对镜片（朝后为正），y 相对机匣导轨的齿顶
  const lo = (pts) => pts.map(([z, y]) => [Z + z, RAIL_Y + y]);
  // 本体：后平台上宽下窄，前后端面都朝外斜上去；前面一段矮腹板托着前伸段的根部
  const body = lo([[0.0365, 0.0002], [0.0414, P - 0.0017], [0.0414, P], [-0.0042, P], [-0.0042, P - 0.0017], [0, 0.0036],
    [-0.0016, E - 0.0063], [-0.02, E - 0.0063], [-0.0224, 0.0002]]);
  // 两侧各铣一个前后边都是斜的减重槽
  const pocket = chamfer(lo([[0.0048, 0.0036], [0.0355, 0.0036], [0.0375, P - 0.0019], [0.001, P - 0.0019]]), 0.0005);
  k.metal(ex(body, 0.016, 0.0005), SIDE());
  for (const s of [-1, 1]) k.metal(ex(body, 0.0016, 0.0005, [pocket]), SIDE(s * 0.0088));

  // 压在齿顶上的底板和两侧夹爪
  const zc = Z + 0.008, len = 0.06, by = RAIL_Y - 0.0018;
  k.metal(rbox(0.022, 0.0028, len - 0.0004, 0.0005, 1), xf(0.0002, RAIL_Y + 0.0016, zc));
  k.metal(ex(JAW_FIX, len, 0.0006), xf(0, RAIL_Y, zc));
  k.metal(ex(JAW_BAR, len, 0.0006), xf(0, RAIL_Y, zc));
  // 两根横栓：左侧凸台里是内六角栓头，右侧露出栓尾
  for (const z of [Z + 0.024, Z - 0.008]) {
    k.metal(ex(BOSS.map(([a, b]) => [z + a, RAIL_Y + b]), 0.0036, 0.0007), SIDE(-0.017));
    screw(k, -0.0186, by, z, -0.0196, by, z, 0.0031);
    k.steel(cylBetween(0.0151, by, z, 0.0158, by, z, 0.0024, 12));
  }

  // 后平台 5 个齿；前伸段 4 个齿，齿顶比后平台矮一截，底下悬空
  rail(k, Z + 0.041, 5, OPTIC.lo);
  rail(k, Z - 0.0102, 4, OPTIC.ext, RAIL_SLIM);
  k.metal(ex(lo([[-0.0449, E - 0.0064], [-0.047, E - 0.0064], [-0.0486, E - 0.0048], [-0.0486, E - 0.003], [-0.0449, E - 0.003]]), 0.0212, 0.0005), SIDE());
}

export function buildUpperRiser(k) {
  const y0 = OPTIC.lo, h = OPTIC.deck - OPTIC.lo, zc = Z + 0.0175, T = h - 0.0035; // T：两个窗的上边，压在顶板底下
  // 侧视轮廓 [z, y]：z 相对支架中心，y 相对后平台的齿顶
  const up = (pts) => pts.map(([z, y]) => [zc + z, y0 + y]);
  // 夹爪咬住后平台，底梁压在齿顶上
  railClamp(k, zc, 0.033, [zc + 0.009, zc - 0.009], y0);
  k.metal(rbox(0.025, 0.0034, 0.033, 0.0006, 1), xf(0, y0 + 0.0017, zc));
  // 侧板上长下短。靠前一个大三角窗，后面一个小一圈的圆角三角窗，中间留一根粗斜撑
  const wall = up([[0.0165, 0.0003], [0.02, h - 0.0022], [0.0187, h], [-0.0187, h], [-0.02, h - 0.0022], [-0.0165, 0.0003]]);
  const front = fillet(up([[-0.0135, 0.0036], [0.006, 0.0036], [-0.0162, T]]), 0.0008, 2);
  const back = fillet(up([[-0.0035, T], [0.0163, T], [0.0138, T * 0.45]]), 0.002, 4);
  for (const s of [-1, 1]) {
    k.metal(ex(wall, 0.0032, 0.0006, [front, back]), SIDE(s * 0.0109));
    // 顶板靠侧面的横螺丝固定
    for (const z of [zc + 0.012, zc - 0.012]) screw(k, s * 0.0122, y0 + h - 0.0017, z, s * 0.0131, y0 + h - 0.0017, z, 0.0013);
  }
  // 顶板夹在两片侧板之间，中间是空的，从后面能看穿
  k.metal(rbox(0.0188, 0.0033, 0.0372, 0.0005, 1), xf(0, y0 + h - 0.00165, zc));
}
