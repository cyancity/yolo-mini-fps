// 骨架式精确射手枪托：带螺纹的缓冲管和城堡螺母，套在管子后半截的平侧面托体，顶上可调的贴腮板，
// 加厚的橡胶托底板，托体下面镂空的钩形框架，管子底下一根伸向机匣的细斜撑
import { box, rbox, lathe, cylBetween, xf } from '../gfx/geo.js';
import { ex, crisp, SIDE, arc, rect, chamfer, slant, loft, ring, screw } from './rifle_kit.js';

const X = [1, 0, 0], Z = [0, 0, 1];
const HW = 0.018; // 托体半宽
const PAD = { top: 0.03, bot: -0.1, r: 0.009 }; // 托底板的上下沿、两头的圆角

function tube(k) {
  k.metal(cylBetween(0, 0, 0.0155, 0, 0, 0.214, 0.0143, 28));
  // 管口一段螺纹
  for (let i = 0; i < 12; i++) k.metal(cylBetween(0, 0, 0.0292 + i * 0.0024, 0, 0, 0.0302 + i * 0.0024, 0.01485, 28));
  // 尾板左下伸出一个背带环耳
  const plate = [...arc(0, 0, 0.019, -60, 200, 26), [-0.0235, -0.012], [-0.0245, -0.024], [-0.017, -0.03], [-0.006, -0.0285]];
  k.metal(ex(plate, 0.0025, 0.0004, [rect(-0.0185, -0.0195, 0.0025, 0.0055, 0.001)]), xf(0, 0, 0.01725));
  // 城堡螺母和一圈扳手口
  k.metal(cylBetween(0, 0, 0.0185, 0, 0, 0.0275, 0.0183, 24));
  for (let i = 0; i < 6; i++) {
    const a = (i * Math.PI) / 3 + 0.5;
    k.black(box(0.0016, 0.0045, 0.0042), xf(Math.cos(a) * 0.0178, Math.sin(a) * 0.0178, 0.0256, 0, 0, a));
  }
  // 管子底下的细斜撑：前端一个抱箍箍在管口，后端接到托体前下角
  k.metal(ex([[0.03, -0.0128], [0.03, -0.0186], [0.118, -0.0288], [0.118, -0.0215]], 0.009, 0.0008), SIDE());
  k.metal(rbox(0.0125, 0.0085, 0.008, 0.0012, 1), xf(0, -0.0158, 0.0345));
  for (const s of [-1, 1]) screw(k, s * 0.0058, -0.0165, 0.0345, s * 0.0069, -0.0165, 0.0345, 0.0016);
}

// 托体：一块平侧面的铣件套在管子后半截上。侧视轮廓 [z, y]
function body(k) {
  const outline = [[0.108, -0.016], [0.108, 0.0135], [0.115, 0.0205], [0.246, 0.0205], [0.246, -0.03], [0.15, -0.03], [0.122, -0.0265], [0.11, -0.021]];
  // 前上角两道斜的减重槽，铣穿了能看到里面的管子
  const slots = [slant(0.1235, 0.0065, 0.0062, 0.002, 62), slant(0.1335, 0.0065, 0.0062, 0.002, 62)];
  // 两侧各有一块下沉的面板，里面是快拆背带座
  const panel = chamfer([[0.166, -0.0245], [0.239, -0.0245], [0.239, 0.006], [0.233, 0.012], [0.172, 0.012], [0.166, 0.006]], 0.0008);
  k.metal(ex(outline, HW * 2 - 0.003, 0.0008, slots), SIDE());
  const socket = [[0.0042, 0], [0.0062, 0], [0.0062, 0.0012], [0.0055, 0.0018], [0.0042, 0.0018], [0.0042, 0.0002]];
  for (const s of [-1, 1]) {
    k.metal(ex(outline, 0.0015, 0.0005, [...slots, panel]), SIDE(s * (HW - 0.00075)));
    k.steel(crisp(lathe(socket, 20)), xf(s * (HW - 0.0015), -0.012, 0.222, 0, 0, (-s * Math.PI) / 2));
    k.black(cylBetween(s * (HW - 0.0018), -0.012, 0.222, s * (HW - 0.0013), -0.012, 0.222, 0.0043, 16));
    // 把托体夹紧在管子上的两颗螺丝
    for (const z of [0.137, 0.158]) screw(k, s * (HW - 0.0002), -0.0225, z, s * (HW + 0.0007), -0.0225, z, 0.0022);
  }
}

// 贴腮板：单独一块矮板，靠两根立柱架在托体顶上，侧面一排六个斜的长圆孔；右侧是锁紧旋钮
function comb(k) {
  for (const z of [0.142, 0.214]) k.steel(cylBetween(0, 0.0195, z, 0, 0.0245, z, 0.0042, 14));
  const holes = Array.from({ length: 6 }, (_, i) => slant(0.1335 + i * 0.0182, 0.0288, 0.0044, 0.0016, 38));
  const plate = [[0.117, 0.0238], [0.117, 0.0292], [0.1215, 0.0338], [0.2365, 0.0338], [0.2405, 0.03], [0.2405, 0.0238]];
  k.poly(ex(plate, 0.03, 0.0012, holes), SIDE());
  // 孔是通的，从侧面会一眼望穿到对面的背景；中间塞一条黑芯，看上去才是一排深槽
  k.black(box(0.02, 0.0088, 0.108), xf(0, 0.0288, 0.179));
  k.steel(cylBetween(HW - 0.0002, 0.0135, 0.178, HW + 0.0036, 0.0135, 0.178, 0.0052, 18));
  k.black(cylBetween(HW + 0.0036, 0.0135, 0.178, HW + 0.0039, 0.0135, 0.178, 0.0021, 6));
}

// 托底板的一片：水平截面一层层叠起来，上下两头收圆。z0 是前表面，zr(y) 是后表面
function slab(k, z0, zr) {
  const { top, bot, r } = PAD, cap = [0, 0.0012, 0.0035, 0.0065], st = [];
  for (const t of cap) st.push([top - t, t]);
  for (let i = 0; i <= 6; i++) st.push([top - r - ((top - bot - 2 * r) * i) / 6, r]);
  for (const t of [...cap].reverse()) st.push([bot + t, t]);
  k.rubber(loft(st.map(([y, t]) => {
    const z1 = zr(y), hx = HW - r + Math.sqrt(r * r - (r - t) * (r - t));
    return ring([0, y, (z0 + z1) / 2], X, Z, hx, (z1 - z0) / 2, 4);
  })));
}

// 加厚的橡胶托底板：比托体高，四片叠起来中间三道竖槽，最后一片的后表面是微微内凹的弧面
function pad(k) {
  const yc = (PAD.top + PAD.bot) / 2, hy = (PAD.top - PAD.bot) / 2;
  k.metal(rbox(0.0345, hy * 2 - 0.002, 0.0034, 0.0012, 1), xf(0, yc, 0.2477));
  k.black(rbox(0.031, hy * 2 - 0.006, 0.022, 0.003, 1), xf(0, yc, 0.2605));
  for (let i = 0; i < 3; i++) slab(k, 0.2492 + i * 0.006, () => 0.2542 + i * 0.006);
  slab(k, 0.2672, (y) => 0.2726 + 0.003 * ((y - yc) / hy) ** 2);
}

// 托体下面的镂空框架：前面一根立柱垂下来，底梁往后接到托底板，前下角往前探出一个钩；中间隔出两个长方窗
function frame(k) {
  const outline = [[0.15, -0.027], [0.15, -0.082], [0.143, -0.0885], [0.138, -0.0905], [0.136, -0.0955], [0.138, -0.101], [0.142, -0.103],
    [0.244, -0.103], [0.248, -0.099], [0.248, -0.027]];
  const holes = [rect(0.1808, -0.0635, 0.0193, 0.0275, 0.002), rect(0.2245, -0.0635, 0.0175, 0.0275, 0.002)];
  k.metal(ex(outline, 0.016, 0.0012, holes), SIDE());
}

export function buildStock(k) {
  tube(k);
  body(k);
  comb(k);
  pad(k);
  frame(k);
}
