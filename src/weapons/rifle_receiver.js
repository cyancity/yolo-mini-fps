// 机匣组：上下机匣、弹匣井和各种操作件，外加拉机柄、枪机、扳机、快慢机四个活动件
import { box, rbox, cylBetween, xf } from '../gfx/geo.js';
import { ex, SIDE, PLAN, arc, curve, strip, rect, chamfer, screw, rail, DECK_Y } from './rifle_kit.js';
import { markSide } from './rifle_marks.js';

const R_BORE = 0.0108, SLOT = 0.0052; // 枪机孔半径、孔顶拉机柄槽的半宽
const HW = 0.01175; // 下机匣半宽
const UW = 0.0128; // 上机匣平侧壁的半宽
const DEG = 180 / Math.PI;
export const PORT = { z0: -0.076, z1: -0.146, yb: -0.006, yt: 0.0095 }; // 抛壳口
export const PIVOT = { handle: [0, 0.0182, 0], bolt: [0, 0, -0.15], trigger: [0, -0.0345, -0.042], selector: [0, -0.03, -0.026] };

// 上机匣右半边截面（自下而上）：平侧壁、斜肩、导轨座两级台阶。FAT 是枪管节套那一段的加厚版
const HALF = [[UW, -0.018], [UW, 0.0045], [0.0092, 0.0115], [0.0092, 0.0155], [0.0084, 0.0163], [0.0084, DECK_Y]];
const FAT = [[0.014, -0.018], [0.014, 0.0052], [0.0104, 0.0122], [0.0092, 0.0132], [0.0092, 0.0155], [0.0084, 0.0163], [0.0084, DECK_Y]];
const mirror = (pts) => pts.map(([x, y]) => [-x, y]);

// 上机匣按截面沿枪管方向拉伸，中间是带拉机柄槽的枪机孔。
// 抛壳口那一段的截面在窗口高度断开成 C 形，窗口就是真的洞，能看到里面的枪机
function upper(k) {
  const aSlot = Math.acos(SLOT / R_BORE) * DEG, bB = Math.asin(PORT.yb / R_BORE) * DEG;
  const E = 0.0005; // 截面拐角的小倒角
  const outline = (half) => chamfer([...half, ...mirror(half).reverse()], E);
  const keyhole = chamfer([[SLOT, 0.0214], [-SLOT, 0.0214], ...arc(0, 0, R_BORE, 180 - aSlot, 360 + aSlot, 34)], E);
  const edge = (y) => {
    const i = HALF.findIndex((p, j) => j > 0 && y <= p[1]), [x0, y0] = HALF[i - 1], [x1, y1] = HALF[i];
    return [x0 + ((x1 - x0) * (y - y0)) / (y1 - y0), y];
  };
  const cShape = chamfer([
    edge(PORT.yt), ...HALF.filter((p) => p[1] > PORT.yt), ...mirror(HALF).reverse(), ...HALF.filter((p) => p[1] < PORT.yb), edge(PORT.yb),
    ...arc(0, 0, R_BORE, bB, -180 - aSlot, 26), [-SLOT, 0.0214], [SLOT, 0.0214], [SLOT, PORT.yt],
  ], E);
  // 段与段之间不倒角，接缝才看不出来
  const seg = (shape, holes, z0, z1) => k.metal(ex(shape, z0 - z1, 0, holes), xf(0, 0, (z0 + z1) / 2));
  seg(outline(HALF), [keyhole], 0, PORT.z0);
  seg(cShape, [], PORT.z0, PORT.z1);
  seg(outline(HALF), [keyhole], PORT.z1, -0.164);
  seg(outline(FAT), [keyhole], -0.164, -0.192);
  k.metal(cylBetween(0, 0, -0.1835, 0, 0, -0.1925, 0.0166, 28)); // 枪管节套凸缘
  rail(k, -0.0035, 19);
}

function lower(k) {
  // 击发机构座 + 握把接口
  const core = [[-0.0655, -0.018], [0.0155, -0.018], [0.0155, -0.03], [0.028, -0.036], [0.029, -0.044], [0.022, -0.048],
    [-0.007, -0.048], [-0.007, -0.0405], [-0.0655, -0.0405]];
  k.metal(ex(core, HW * 2, 0.0012), SIDE());
  // 前铰接座
  k.metal(ex([[-0.134, -0.018], [-0.16, -0.018], [-0.166, -0.0235], [-0.16, -0.0335], [-0.134, -0.04]], HW * 2, 0.0012), SIDE());
  // 缓冲管座：顶上削平给拉机柄让路
  const tower = [...arc(0, 0, 0.0178, -48.5, 56.3, 12), ...arc(0, 0, 0.0178, 123.7, 228.5, 12), [-0.0118, -0.03], [0.0118, -0.03]];
  k.metal(ex(tower, 0.016, 0.001), xf(0, 0, 0.008));
  // 弹匣井：俯视轮廓带内孔，沿 Y 拉伸，弹匣真能插进去；前脸一排防滑齿
  const teeth = Array.from({ length: 13 }, (_, i) => [0.0108 - i * 0.0018, 0.137 - (i % 2) * 0.0009]);
  const well = [[-0.0145, 0.066], [-0.0115, 0.063], [0.0115, 0.063], [0.0145, 0.066], [0.0145, 0.134], [0.0118, 0.137], ...teeth, [-0.0118, 0.137], [-0.0145, 0.134]];
  const hole = rect(0, 0.1, 0.0119, 0.0315, 0.0015);
  k.metal(ex(well, 0.046, 0.0008, [hole]), PLAN(-0.041));
  k.metal(ex(rect(0, 0.1, 0.0158, 0.0388, 0.0035), 0.0062, 0.0012, [hole]), PLAN(-0.0652)); // 井口喇叭边
  // 扳机护圈
  const guard = strip(curve([[-0.064, -0.046], [-0.06, -0.06], [-0.05, -0.0685], [-0.034, -0.0715], [-0.02, -0.0705], [-0.0105, -0.064], [-0.006, -0.05]], 4), 0.0036);
  k.metal(ex(guard, 0.012, 0.0009), SIDE());
  // 销：扳机销、击锤销贯穿两侧；分解销和铰接销左侧带销帽
  const pin = (z, y, r, hw) => k.steel(cylBetween(-hw, y, z, hw, y, z, r, 12));
  pin(-0.042, -0.0345, 0.0019, HW + 0.0004);
  pin(-0.058, -0.027, 0.0019, HW + 0.0004);
  for (const [z, y] of [[-0.005, -0.0225], [-0.156, -0.0235]]) {
    pin(z, y, 0.0027, HW + 0.0006);
    k.steel(cylBetween(-HW - 0.0016, y, z, -HW, y, z, 0.0037, 16));
    k.black(cylBetween(HW, y, z, HW + 0.0009, y, z, 0.0011, 8));
  }
}

function controls(k) {
  // 左侧：空仓挂机拨片（上大下小）、弹匣卡笋横杆
  k.metal(rbox(0.004, 0.0105, 0.0125, 0.0012, 1), xf(-0.015, -0.0105, -0.0665));
  k.metal(rbox(0.003, 0.009, 0.005, 0.0008, 1), xf(-0.0147, -0.0185, -0.0665));
  k.metal(rbox(0.0035, 0.007, 0.009, 0.001, 1), xf(-0.0155, -0.0245, -0.0665));
  for (let i = 0; i < 4; i++) k.black(box(0.0005, 0.0006, 0.0105), xf(-0.01705, -0.0069 - i * 0.0024, -0.0665));
  k.metal(rbox(0.0018, 0.0046, 0.021, 0.0006, 1), xf(-0.0152, -0.0335, -0.0735));
  screw(k, -0.0145, -0.0335, -0.0815, -0.0168, -0.0335, -0.0815, 0.0024);
  // 右侧：弹匣释放钮和护圈
  k.metal(ex(arc(-0.0725, -0.0335, 0.0078, 0, 342, 19), 0.0022, 0.0005, [arc(-0.0725, -0.0335, 0.006, 0, 337.5, 15)]), SIDE(0.0156));
  k.metal(cylBetween(0.0143, -0.0335, -0.0725, 0.0163, -0.0335, -0.0725, 0.0052, 16));
  for (let i = -1; i <= 1; i++) k.black(box(0.0005, 0.0008, 0.0072), xf(0.01635, -0.0335 + i * 0.0023, -0.0725));
  // 右侧：抛壳挡块、复进助推器
  k.metal(ex([[0.0112, 0.059], [0.0112, 0.0755], [0.0205, 0.0635]], 0.016, 0.0008), PLAN(0.003));
  k.metal(cylBetween(0.0162, 0.004, -0.06, 0.0188, 0.004, -0.026, 0.0062, 16));
  k.steel(cylBetween(0.0188, 0.004, -0.026, 0.0199, 0.004, -0.013, 0.0046, 14));
  k.steel(cylBetween(0.0197, 0.004, -0.0155, 0.02, 0.004, -0.012, 0.0057, 16));
  k.black(cylBetween(0.02, 0.004, -0.012, 0.02002, 0.004, -0.0117, 0.0014, 8));
  // 右侧：防尘盖打开垂在抛壳口下面，铰链轴沿窗口下沿
  k.steel(cylBetween(0.0139, -0.0068, -0.15, 0.0139, -0.0068, -0.072, 0.0011, 8));
  for (const z of [-0.142, -0.111, -0.08]) k.metal(cylBetween(0.0139, -0.0068, z - 0.006, 0.0139, -0.0068, z + 0.006, 0.002, 10));
  k.metal(rbox(0.0016, 0.021, 0.074, 0.0006, 1), xf(0.0161, -0.0171, -0.111, 0, 0, 0.209));
  k.metal(rbox(0.0012, 0.012, 0.05, 0.0005, 1), xf(0.01727, -0.01685, -0.111, 0, 0, 0.209));
  k.steel(cylBetween(0.01743, -0.02343, -0.111, 0.0199, -0.0229, -0.111, 0.0016, 10));
}

export function buildReceiver(k) {
  upper(k);
  lower(k);
  controls(k);
  markSide(k, 'main', 0.0306, -0.0145, -0.0445, -0.104);
  markSide(k, 'logo', 0.018, 0.0145, -0.047, -0.1);
  markSide(k, 'cal', 0.0036, -UW, -0.0125, -0.118);
  for (const s of [-1, 1]) {
    markSide(k, 'auto', 0.0032, s * HW, -0.0302, -0.0478);
    markSide(k, 'semi', 0.0032, s * HW, -0.0212, -0.037);
    markSide(k, 'safe', 0.0032, s * HW, -0.0216, -0.0168);
  }
}

// 拉机柄：T 形头露在机匣后面，杆身藏在枪机孔上方的槽里，后拉时才抽出来
export function buildChargingHandle(k) {
  const teeth = Array.from({ length: 11 }, (_, i) => [-0.011 + i * 0.0022, -0.0125 + (i % 2) * 0.0008]);
  const outline = [[0.0045, 0.15], [-0.0045, 0.15], [-0.0045, -0.0006], [-0.0205, -0.0006], [-0.0225, -0.004], [-0.0215, -0.0085], [-0.0125, -0.0125],
    ...teeth, [0.0125, -0.0125], [0.0215, -0.0085], [0.0225, -0.004], [0.0205, -0.0006], [0.0045, -0.0006]];
  k.metal(ex(outline, 0.006, 0.001), PLAN(0.0182));
  for (const s of [-1, 1]) k.metal(rbox(0.0105, 0.0012, 0.0062, 0.0004, 1), xf(s * 0.0152, 0.0215, 0.0052));
  screw(k, -0.0105, 0.0205, 0.0052, -0.0105, 0.0224, 0.0052, 0.0013, false);
  screw(k, 0.0105, 0.0205, 0.0052, 0.0105, 0.0224, 0.0052, 0.0013, false);
}

// 枪机组：机框是一根贴着枪机孔的钢柱，后坐时整体滑进缓冲管
export function buildBolt(k) {
  k.steel(cylBetween(0, 0, -0.012, 0, 0, -0.15, 0.0102, 28));
  k.steel(cylBetween(0, 0, -0.15, 0, 0, -0.163, 0.0066, 16));
  for (let i = 0; i < 7; i++) {
    const a = (i / 7) * Math.PI * 2 + 0.3;
    k.steel(box(0.0024, 0.0026, 0.0045), xf(Math.cos(a) * 0.0072, Math.sin(a) * 0.0072, -0.1605, 0, 0, a));
  }
  k.steel(rbox(0.003, 0.0045, 0.012, 0.0008, 1), xf(0.0062, 0.0022, -0.155));
  for (const z of [-0.139, -0.127]) k.black(cylBetween(0, 0, z, 0, 0, z - 0.0012, 0.01035, 28));
  // 助推器咬合齿，正对抛壳口
  for (let i = 0; i < 9; i++) k.black(box(0.0008, 0.0042, 0.0013), xf(0.00945, 0.00421, -0.084 - i * 0.0028, 0, 0, 0.42));
}

export function buildTrigger(k) {
  const blade = strip(curve([[-0.0422, -0.033], [-0.0425, -0.04], [-0.0434, -0.047], [-0.0452, -0.0535], [-0.0462, -0.0585], [-0.045, -0.063]], 3), 0.0048);
  k.steel(ex(blade, 0.0068, 0.001), SIDE());
}

// 快慢机：建模姿态拨杆朝前（AUTO），绕 X 正转 1.2 到 SEMI、2.4 到 SAFE；两侧同轴
export function buildSelector(k) {
  const [, y, z] = PIVOT.selector;
  k.metal(cylBetween(-HW + 0.0002, y, z, -0.014, y, z, 0.0046, 16));
  k.metal(rbox(0.0026, 0.0048, 0.016, 0.001, 1), xf(-0.0147, y, z - 0.008));
  k.metal(rbox(0.0036, 0.0054, 0.0042, 0.001, 1), xf(-0.0152, y, z - 0.0142));
  screw(k, -0.014, y, z, -0.0162, y, z, 0.0022);
  k.metal(cylBetween(HW - 0.0002, y, z, 0.0136, y, z, 0.0042, 16));
  k.metal(rbox(0.0022, 0.0042, 0.011, 0.0008, 1), xf(0.0142, y, z - 0.0055));
  screw(k, 0.0136, y, z, 0.0155, y, z, 0.002);
}
